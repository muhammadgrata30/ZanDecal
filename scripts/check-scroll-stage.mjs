import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('../lib/scroll-stage.ts',import.meta.url),'utf8');
const exports={};
new Function('exports',ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(exports);
const {stageLayout,stageProgress}=exports;
const tall=stageLayout(1400,800,88,.45,1,false);
assert.deepEqual(tall,{sticky:false,top:0,height:1400},'Tall content has no negative sticky offset or empty runway');
const fit=stageLayout(650,800,88,.45,1,false);
assert.deepEqual(fit,{sticky:true,top:88,height:1010},'A fitting panel keeps its sticky animation');
assert.equal(stageLayout(650,800,88,.45,1,true).height,650);
const progress=top=>stageProgress(top,1400,tall.height,800,0,false,false);
const positions=Array.from({length:221},(_,i)=>800-i*10);
const down=positions.map(progress),up=[...positions].reverse().map(progress);
assert.equal(down[0],0);assert.equal(down.at(-1),1);
for(let i=1;i<down.length;i++)assert.ok(down[i]>=down[i-1]&&down[i]-down[i-1]<.005,'Normal-flow motion advances gradually');
assert.deepEqual(up,[...down].reverse(),'Reversing scroll retraces the same motion without threshold jumps');
assert.equal(stageProgress(88,650,fit.height,800,88,true,false),0);
assert.equal(stageProgress(-272,650,fit.height,800,88,true,false),1);
assert.equal(stageProgress(800,1400,1400,800,0,false,true),1);
console.log('PASS: tall content in flow, fitting sticky panels, continuous bidirectional progress and reduced motion.');
