import assert from "node:assert/strict";

const html = await (await fetch("http://localhost:3000/", { signal: AbortSignal.timeout(60000) })).text();
const content = await (await fetch("http://localhost:3000/api/content", { signal: AbortSignal.timeout(30000) })).json();
const start = html.search(/<section\b[^>]*\bid="material"/);
assert.ok(start >= 0, "Homepage contains integrated material section");
const section = html.slice(start, html.indexOf("</section>", start) + 10);
assert.equal((html.match(/\bid="material"/g) || []).length, 1);
assert.equal((html.match(/\bid="material-detail"/g) || []).length, 1);
assert.equal((html.match(/\bid="material-specification"/g) || []).length, 1);
assert.ok(section.includes("BEDANYA"));
assert.ok(section.includes("Koleksi"));
assert.ok(section.includes('aria-label="Spesifikasi bahan pilihan"'));
assert.ok(section.includes("<dl>"), "Specifications are already visible, not behind a disclosure");
assert.ok(!section.includes("<summary"), "No specification disclosure button");
assert.ok(!/<input[^>]*type="range"/.test(section), "No adjustable rollout slider");
assert.ok(!section.includes("Bentangkan bahan"));
assert.ok(section.includes('class="hm-decal-image"'), "Decal is server-rendered as an accessible vector image");
assert.ok(section.includes('attributeName="d"'), "Image outline has wind motion");
assert.ok(!section.includes("<canvas"), "Material section uses no WebGL canvas");
for (const finish of ["Gloss", "Satin", "Matte"]) assert.ok(section.includes(`>${finish}</button>`), "All finishes remain selectable");
assert.ok(section.includes("Jeda animasi decal"), "Wind motion can be paused");
assert.equal((section.match(/aria-controls="material-specification"/g) || []).length, content.materials.length, "Every published material controls the same direct specification region");
const escape = value => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&#x27;");
for (const color of content.colors) assert.ok(section.includes(`aria-label="${escape(color.name)}"`), "Admin colors remain selectable");
assert.ok(html.includes('class="perfect-apply"') && html.includes('id="3d-studio"'), "Current 3D hero and separate interactive studio remain present");
assert.ok(html.includes('id="konsultasi"'));
assert.ok(html.includes('id="galeri"'));
console.log("Homepage integration passed: accessible 2D decal with wind and pause, three finishes, full admin palette, unique anchors, direct material specifications and retained hero/studio/gallery/consultation.");
